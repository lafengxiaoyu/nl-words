-- ============================================
-- 定期清理 API 日志的定时任务
-- ============================================
--
-- 此脚本设置每月自动清理 90 天前的 API 使用日志
--
-- 注意：Supabase 免费套餐需要手动启用 pg_cron 扩展
-- 进入 Dashboard > Database > Extensions > 搜索 pg_cron > Enable
--
-- ============================================

-- 1. 确保 pg_cron 扩展已启用
-- 如果提示扩展不存在，请在 Supabase Dashboard 中手动启用

-- 2. 创建清理函数（如果还没有）
CREATE OR REPLACE FUNCTION cleanup_old_api_logs()
RETURNS void AS $$
BEGIN
  DELETE FROM api_usage_log
  WHERE created_at < NOW() - INTERVAL '90 days';

  RAISE NOTICE '已清理超过 90 天的 API 日志';
END;
$$ LANGUAGE plpgsql;

-- 3. 设置定时任务：每月 1 号凌晨 2 点执行
-- 删除 30 天前的日志
SELECT cron.schedule(
  'cleanup-api-logs-monthly',
  '0 2 1 * *',  -- Cron 表达式：每月 1 号凌晨 2 点
  $$SELECT cleanup_old_api_logs()$$
);

-- ============================================
-- Cron 表达式说明：
-- ============================================
--
-- 格式：分 时 日 月 周
--
-- '0 2 1 * *'  = 每月 1 号凌晨 2:00
-- '0 3 * * 0'  = 每周日凌晨 3:00
-- '0 1 * * *'  = 每天凌晨 1:00
-- '0 */6 * * *' = 每 6 小时
--
-- ============================================

